#!/usr/bin/env python3
"""Regenerate test/test_protocol/vectors.h from the Python reference
implementation (rabits/ha-ef-ble). Run when the reference repo or the vector
set changes:

    python3 tools/gen_test_vectors.py /path/to/ha-ef-ble

The generated vectors are byte-for-byte outputs of the reference code
(packet framing, EncPacket encryption, session-key derivation), so the C++
port in src/ef/ can be validated without hardware.
"""

import hashlib
import struct
import sys
import tempfile
from pathlib import Path

REPO = Path(sys.argv[1] if len(sys.argv) > 1 else "../ha-ef-ble")
EFLIB = REPO / "custom_components" / "ef_ble" / "eflib"

# The reference modules use relative imports but eflib/__init__.py drags in
# bleak/HA deps, so mirror just the stdlib-only modules into a shim package.
shim = Path(tempfile.mkdtemp()) / "eflib_ref"
shim.mkdir()
(shim / "__init__.py").write_text("")
for mod in ("crc.py", "packet.py", "keydata.py"):
    (shim / mod).write_text((EFLIB / mod).read_text())
sys.path.insert(0, str(shim.parent))

from eflib_ref import crc, keydata  # noqa: E402
from eflib_ref.packet import Packet  # noqa: E402

from Crypto.Cipher import AES  # noqa: E402
from Crypto.Util.Padding import pad  # noqa: E402


def enc_frame(frame_type: int, payload: bytes) -> bytes:
    """EncPacket.to_bytes / SimplePacketAssembler.encode (encpacket.py)"""
    data = b"\x5a\x5a" + struct.pack("<B", frame_type << 4) + b"\x01"
    data += struct.pack("<H", len(payload) + 2)
    data += payload
    data += struct.pack("<H", crc.crc16(data))
    return data


def type7_encrypt(key: bytes, iv: bytes, plaintext: bytes) -> bytes:
    return AES.new(key, AES.MODE_CBC, iv).encrypt(pad(plaintext, 16))


def gen_session_key(seed: bytes, srand: bytes) -> bytes:
    """connection.py Connection.genSessionKey, verbatim logic"""
    pos = seed[0] * 0x10 + ((seed[1] - 1) & 0xFF) * 0x100
    data = keydata.get8bytes(pos) + keydata.get8bytes(pos + 8) + srand[0:8] + srand[8:16]
    return hashlib.md5(data).digest()


out = []


def emit(name: str, data: bytes) -> None:
    hex_bytes = ", ".join(f"0x{b:02x}" for b in data)
    out.append(f"static const uint8_t {name}[] = {{{hex_bytes}}};")
    out.append(f"static const size_t {name}_len = {len(data)};")


# 1. CRC vectors
sample = bytes(range(1, 32))
out.append(f"static const uint8_t CRC8_SAMPLE = 0x{crc.crc8(sample):02x};")
out.append(f"static const uint16_t CRC16_SAMPLE = 0x{crc.crc16(sample):04x};")
emit("CRC_INPUT", sample)

# 2. Command packets (river2.py enable_ac_ports / enable_dc_12v_port)
emit("PKT_AC_ON", Packet(0x21, 0x05, 0x20, 0x42,
                         bytes([1, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF]),
                         version=2).to_bytes())
emit("PKT_DC_OFF", Packet(0x21, 0x05, 0x20, 0x51, bytes([0]), version=2).to_bytes())

# 3. Auth packets (connection.py getAuthStatus / autoAuthentication)
emit("PKT_AUTH_STATUS", Packet(0x21, 0x35, 0x35, 0x89, b"", 0x01, 0x01, 2).to_bytes())
user_id, sn = "1234567890123456789", "R621ZAB1TEST0001"
md5_data = hashlib.md5((user_id + sn).encode("ASCII")).digest()
auth_payload = ("".join(f"{c:02X}" for c in md5_data)).encode("ASCII")
emit("PKT_AUTH_SUBMIT", Packet(0x21, 0x35, 0x35, 0x86, auth_payload, 0x01, 0x01, 2).to_bytes())

# 4. A V2 telemetry-style packet for decode tests (MPPT heartbeat shape)
mppt_payload = bytes(range(94))
telemetry = Packet(0x05, 0x21, 0x20, 0x02, mppt_payload, version=2,
                   seq=b"\x11\x22\x33\x44")
emit("PKT_TELEMETRY", telemetry.to_bytes())
emit("PKT_TELEMETRY_PAYLOAD", mppt_payload)

# 5. A V3 packet (decode-path coverage)
emit("PKT_V3", Packet(0x35, 0x21, 0x35, 0x86, b"\x00", 0x01, 0x01, 3).to_bytes())

# 6. SimplePacket handshake frame (pubkey exchange shape)
pubkey = bytes(range(40))
emit("SIMPLE_PUBKEY_FRAME", enc_frame(0x00, b"\x01\x00" + pubkey))

# 7. Session key derivation (keydata table + MD5)
seed, srand = bytes([0x0A, 0x02]), bytes(range(0x30, 0x40))
emit("SESSION_SEED", seed)
emit("SESSION_SRAND", srand)
emit("SESSION_KEY", gen_session_key(seed, srand))

# 8. Full encrypted type-7 frame: EncPacket(frame_type=1) around AES(packet)
key = bytes(range(16))
iv = bytes(range(0x50, 0x60))
emit("T7_KEY", key)
emit("T7_IV", iv)
inner = telemetry.to_bytes()
emit("T7_FRAME", enc_frame(0x01, type7_encrypt(key, iv, inner)))

# 9. Type-7 keyinfo response payload: 0x02 || AES(sRand + seed)
emit("KEYINFO_PAYLOAD", b"\x02" + type7_encrypt(key, iv, srand + seed))

header = (
    "// Generated by tools/gen_test_vectors.py from the ha-ef-ble reference\n"
    "// implementation — do not edit by hand.\n"
    "#pragma once\n\n#include <stddef.h>\n#include <stdint.h>\n\n"
)
dest = Path(__file__).resolve().parent.parent / "test" / "test_protocol" / "vectors.h"
dest.write_text(header + "\n".join(out) + "\n")
print(f"wrote {dest}")
